const moduleList = document.getElementById('module-list');
const moduleDetails = document.getElementById('module-details');
const moduleTitle = document.getElementById('selected-module-title');
const editBtn = document.getElementById('edit-btn');

let currentModuleId = null;
let isEditing = false;

let builderModules = [];

function init() {
    renderModuleList();
    initBuilder();
    
    // Select no module by default to show dashboard
    selectModule(null);

    editBtn.addEventListener('click', toggleEditMode);
    
    const searchInput = document.getElementById('module-search');
    searchInput.addEventListener('input', (e) => {
        const query = e.target.value.toLowerCase();
        renderModuleList(query);
    });

    document.getElementById('add-module-btn').addEventListener('click', addNewModule);
}

function initBuilder() {
    const dropZone = document.getElementById('drop-zone');
    
    dropZone.addEventListener('dragover', (e) => {
        e.preventDefault();
        dropZone.classList.add('drag-over');
    });
    
    dropZone.addEventListener('dragleave', () => {
        dropZone.classList.remove('drag-over');
    });
    
    dropZone.addEventListener('drop', (e) => {
        e.preventDefault();
        dropZone.classList.remove('drag-over');
        const moduleId = e.dataTransfer.getData('moduleId');
        if (moduleId) addModuleToBuilder(moduleId);
    });
}

function handleDragStart(e, moduleId) {
    e.dataTransfer.setData('moduleId', moduleId);
}

function addModuleToBuilder(moduleId) {
    const module = modules.find(m => m.id === moduleId);
    if (module) {
        builderModules.push({...module, builderId: Date.now() + Math.random()});
        renderBuilderList();
    }
}

function renderBuilderList() {
    const builderList = document.getElementById('builder-list');
    const dropPlaceholder = document.querySelector('.drop-placeholder');
    const actions = document.getElementById('dashboard-actions');
    
    if (builderModules.length > 0) {
        dropPlaceholder.style.display = 'none';
        actions.style.display = 'flex';
        builderList.innerHTML = builderModules.map((m, index) => `
            <li class="builder-item animate-in" draggable="true" ondragstart="handleBuilderDragStart(event, ${index})" ondragover="handleBuilderDragOver(event)" ondrop="handleBuilderDrop(event, ${index})">
                <div class="module-info">
                    <span class="module-name">${m.title}</span>
                    <span class="module-meta">${m.assessments.length} Assessments</span>
                </div>
                <button class="remove-item-btn" onclick="removeModuleFromBuilder(${index})">×</button>
            </li>
        `).join('');
    } else {
        dropPlaceholder.style.display = 'block';
        actions.style.display = 'none';
        builderList.innerHTML = '';
    }
}

function handleBuilderDragStart(e, index) {
    e.dataTransfer.setData('builderIndex', index);
}

function handleBuilderDragOver(e) {
    e.preventDefault();
}

function handleBuilderDrop(e, toIndex) {
    e.preventDefault();
    const fromIndex = e.dataTransfer.getData('builderIndex');
    if (fromIndex !== "") {
        const item = builderModules.splice(fromIndex, 1)[0];
        builderModules.splice(toIndex, 0, item);
        renderBuilderList();
    }
}

function removeModuleFromBuilder(index) {
    builderModules.splice(index, 1);
    renderBuilderList();
}

function clearBuilder() {
    builderModules = [];
    renderBuilderList();
}

